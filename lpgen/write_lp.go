package lpgen

import (
	"fmt"
	"io"
	"strings"
)

// WriteLP writes the model in CPLEX LP format, using the same bytes as
// GenerateLPFile.
func (lp *LPModel) WriteLP(w io.Writer) error {
	if _, err := io.WriteString(w, "\\Generated by Insyra.\n\\Visit https://insyra.hazelnut-paradise.com for more information.\n\n"); err != nil {
		return err
	}

	var sense string
	switch strings.ToLower(strings.TrimSpace(lp.ObjectiveType)) {
	case "minimize", "min", "minimum":
		sense = "MIN"
	case "maximize", "max", "maximum":
		sense = "MAX"
	default:
		return fmt.Errorf("unknown ObjectiveType %q (expected Minimize/Maximize)", lp.ObjectiveType)
	}

	var b strings.Builder
	b.WriteString(sense + "\n")
	b.WriteString("  obj: " + lp.Objective + "\n")
	b.WriteString("Subject To\n")
	for i, constraint := range lp.Constraints {
		fmt.Fprintf(&b, "  c%d: %s\n", i+1, constraint)
	}
	writeSection := func(title string, lines []string) {
		if len(lines) == 0 {
			return
		}
		b.WriteString(title + "\n")
		for _, line := range lines {
			b.WriteString("  " + line + "\n")
		}
	}
	writeSection("Bounds", lp.Bounds)
	writeSection("General", lp.IntegerVars)
	writeSection("Binary", lp.BinaryVars)
	b.WriteString("End\n")
	_, err := io.WriteString(w, b.String())
	return err
}
